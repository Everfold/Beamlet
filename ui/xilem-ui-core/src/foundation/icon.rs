type IconCacheMap = HashMap<(&'static str, [u8; 4]), Arc<usvg::Tree>>;

/// Parses and caches a 24×24 SVG icon colored with `color`.
#[must_use]
pub fn cached_icon_tree(svg_path: &'static str, color: Color) -> Arc<usvg::Tree> {
    static CACHE: OnceLock<Mutex<IconCacheMap>> = OnceLock::new();
    let rgba = color.to_rgba8();
    let key = (svg_path, [rgba.r, rgba.g, rgba.b, rgba.a]);
    let map = CACHE.get_or_init(|| Mutex::new(HashMap::new()));
    let mut guard = map.lock().unwrap_or_else(|e| e.into_inner());
    if let Some(tree) = guard.get(&key) {
        return tree.clone();
    }

    let opacity = f32::from(rgba.a) / 255.0;
    let markup = format!(
        "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 24 24\" width=\"24\" height=\"24\">\
         <path d=\"{svg_path}\" fill=\"rgb({},{},{})\" fill-opacity=\"{opacity:.3}\"/>\
         </svg>",
        rgba.r, rgba.g, rgba.b
    );
    let tree = Arc::new(
        usvg::Tree::from_str(&markup, &usvg::Options::default())
            .expect("built-in icon SVG markup must always parse cleanly"),
    );
    guard.insert(key, tree.clone());
    tree
}

/// Renders an SVG `<path d="..."/>` icon at `size_px × size_px` tinted with `color`.
pub fn ui_icon<State: 'static, Action: 'static>(
    svg_path: &'static str,
    size_px: f64,
    color: Color,
) -> impl xilem::WidgetView<State, Action> + use<State, Action> {
    let tree = cached_icon_tree(svg_path, color);
    sized_box(svg(tree)).dims(Dimensions::fixed(size_px.px(), size_px.px()))
}
